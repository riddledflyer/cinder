static int is_cjk_name(const char *s) {
    const unsigned char *p = (const unsigned char *)s;
    while (*p) {
        if (*p >= 0xE3) return 1;
        p++;
    }
    return 0;
}

static void fold_ascii(char *dst, size_t cap, const char *src) {
    size_t n = 0;
    int space = 0;
    if (cap == 0) return;
    for (const unsigned char *p = (const unsigned char *)src; *p && n + 1 < cap; ) {
        unsigned char c = *p++;
        char outc = 0;
        if (c < 0x80) {
            if (c >= 'A' && c <= 'Z') outc = (char)(c - 'A' + 'a');
            else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) outc = (char)c;
            else if (c == '&') {
                if (n + 5 < cap) {
                    memcpy(dst + n, " and ", 5);
                    n += 5;
                }
                space = 0;
                continue;
            } else outc = ' ';
        } else if (c == 0xC3 && *p) {
            unsigned char nch = *p++;
            static const char acc[] = "aaaaaaaceeeeiiiidnooooo o";
            if (nch >= 0xA0 && nch <= 0xB8) outc = acc[nch - 0xA0];
            else outc = ' ';
        } else if (c >= 0xC0 && *p) {
            if ((c & 0xE0) == 0xC0) p++;
            else if ((c & 0xF0) == 0xE0 && p[0] && p[1]) p += 2;
            else if ((c & 0xF8) == 0xF0 && p[0] && p[1] && p[2]) p += 3;
            outc = ' ';
        } else outc = ' ';
        if (outc == ' ') {
            if (n && !space && n + 1 < cap) {
                dst[n++] = ' ';
                space = 1;
            }
            continue;
        }
        dst[n++] = outc;
        space = 0;
    }
    while (n && dst[n - 1] == ' ') n--;
    dst[n] = '\0';
    for (;;) {
        static const char *suf[] = {" incorporated"," limited"," corporation"," company"," games"," game"," entertainment"," publishing"," software"," interactive"," studios"," studio"," productions"," production"," digital"," online"," international"," worldwide"," usa"," europe"," japan"," america"," inc"," ltd"," llc"," corp"," co"," gmbh"," plc"};
        int cut = 0;
        for (unsigned i = 0; i < sizeof(suf) / sizeof(suf[0]); i++) {
            size_t sl = strlen(suf[i]);
            if (n > sl && strcmp(dst + n - sl, suf[i]) == 0) {
                n -= sl;
                while (n && dst[n - 1] == ' ') n--;
                dst[n] = '\0';
                cut = 1;
                break;
            }
        }
        if (!cut) break;
    }
    if (strncmp(dst, "the ", 4) == 0) memmove(dst, dst + 4, strlen(dst + 4) + 1);
}

static int prefix_at(const char *longer, const char *shorter) {
    size_t n = strlen(shorter);
    if (n < 4) return 0;
    if (strncmp(longer, shorter, n) != 0) return 0;
    return longer[n] == '\0' || longer[n] == ' ';
}

static int ascii_hit(const char *folded) {
    unsigned n = (unsigned)(sizeof(k_names) / sizeof(k_names[0]));
    unsigned lo = 0, hi = n;
    while (lo < hi) {
        unsigned mid = lo + (hi - lo) / 2;
        int cmp = strcmp(folded, k_names[mid]);
        if (cmp == 0) return 1;
        if (cmp < 0) hi = mid;
        else lo = mid + 1;
    }
    for (unsigned i = 0; i < n; i++) {
        if (prefix_at(folded, k_names[i]) || prefix_at(k_names[i], folded)) return 1;
    }
    return 0;
}

static void fold_jp(char *dst, size_t cap, const char *src) {
    size_t n = 0;
    const char *corp = "\xE6\xA0\xAA\xE5\xBC\x8F\xE4\xBC\x9A\xE7\xA4\xBE";
    for (size_t i = 0; src[i] && n + 1 < cap; ) {
        if ((unsigned char)src[i] == ' ' || (unsigned char)src[i] == '\t') { i++; continue; }
        if ((unsigned char)src[i] == 0xE3 && (unsigned char)src[i+1] == 0x80 && (unsigned char)src[i+2] == 0x80) { i += 3; continue; }
        if ((unsigned char)src[i] == 0xE3 && (unsigned char)src[i+1] == 0x83 && (unsigned char)src[i+2] == 0xBB) { i += 3; continue; }
        if (strncmp(src + i, corp, 12) == 0) { i += 12; continue; }
        unsigned char c = (unsigned char)src[i];
        int len = 1;
        if ((c & 0xE0) == 0xC0) len = 2;
        else if ((c & 0xF0) == 0xE0) len = 3;
        else if ((c & 0xF8) == 0xF0) len = 4;
        if (n + (size_t)len >= cap) break;
        memcpy(dst + n, src + i, (size_t)len);
        n += (size_t)len;
        i += (size_t)len;
    }
    dst[n] = '\0';
}

static int jp_hit(const char *publisher) {
    char folded[128];
    fold_jp(folded, sizeof(folded), publisher);
    if (!folded[0]) return 0;
    unsigned n = (unsigned)(sizeof(k_jp) / sizeof(k_jp[0]));
    for (unsigned i = 0; i < n; i++) {
        size_t kn = strlen(k_jp[i]);
        if (strcmp(folded, k_jp[i]) == 0) return 1;
        if (kn >= 9 && strstr(folded, k_jp[i])) return 1;
    }
    return 0;
}

bool titles_is_licensed(const char *publisher) {
    char folded[96];
    if (!publisher || !publisher[0] || strcmp(publisher, "-") == 0) return false;
    fold_ascii(folded, sizeof(folded), publisher);
    if (folded[0] && ascii_hit(folded)) return true;
    if (is_cjk_name(publisher) && jp_hit(publisher)) return true;
    return false;
}

